// Language name in its own language, in the order the flags are shown.
export const LANGS = { en: 'English', el: 'Ελληνικά', es: 'Español', pt: 'Português', fr: 'Français', de: 'Deutsch' };
export let lang = 'en';
export function setLang(code) { if (DICT[code]) lang = code; return lang; }
// The first of the device's languages we have (e.g. 'el-GR' → 'el'), else English.
export const pickLang = (saved, wanted = []) => DICT[saved] ? saved : wanted.map(l => String(l).slice(0, 2)).find(l => DICT[l]) || 'en';

export function t(key, ...args) {
  const v = DICT[lang][key] ?? DICT.en[key];
  return typeof v === 'function' ? v(...args) : v;
}

// Flags as 15×9 pixel pictures: the colour of pixel (x, y).
const FLAG_W = 15, FLAG_H = 9;
export const FLAG_SIZE = [FLAG_W, FLAG_H];
export function flagPx(code, x, y) {
  if (code === 'en') { // Union flag: white-edged red cross over white-edged red diagonals on blue
    const dx = x - 7, dy = y - 4, d = Math.min(Math.abs(dy * 1.75 - dx), Math.abs(dy * 1.75 + dx));
    if (dx === 0 || dy === 0) return [200, 16, 46];
    if (Math.abs(dx) <= 1 || Math.abs(dy) <= 1) return [255, 255, 255];
    return d < 0.9 ? [200, 16, 46] : d < 1.9 ? [255, 255, 255] : [1, 33, 105];
  }
  if (code === 'el') { // nine stripes; white cross on the blue square
    const blue = [13, 94, 175], white = [255, 255, 255];
    if (x < 5 && y < 5) return x === 2 || y === 2 ? white : blue;
    return y % 2 ? white : blue;
  }
  if (code === 'es') return y < 2 || y > 6 ? [198, 11, 30] : [255, 196, 0];
  if (code === 'pt') return Math.hypot(x - 6, y - 4) < 1.6 ? [255, 204, 0] : x < 6 ? [0, 102, 0] : [255, 0, 0];
  if (code === 'fr') return x < 5 ? [0, 35, 149] : x < 10 ? [255, 255, 255] : [237, 41, 57];
  if (code === 'de') return y < 3 ? [0, 0, 0] : y < 6 ? [221, 0, 0] : [255, 206, 0];
  return [128, 128, 128];
}

